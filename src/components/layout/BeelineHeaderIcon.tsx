const DELAY_MS = 3000;
const ACTIVE_YELLOW = "#FFD93A";

export function BeelineHeaderIcon({
  className,
  onClick,
  isActive = false,
}: {
  className?: string;
  onClick?: () => void;
  isActive?: boolean;
}) {
  const [showAlert, setShowAlert] = useState(false);

  useEffect(() => {
    const timer = setTimeout(() => {
      setShowAlert(true);
    }, DELAY_MS);
    return () => clearTimeout(timer);
  }, []);

  const fillColor = isActive ? ACTIVE_YELLOW : "#202020";
  const flowerFill = isActive ? ACTIVE_YELLOW : showAlert ? "#E00900" : "#202020";
  const circleFill = isActive ? ACTIVE_YELLOW : "#E00900";
  const showCircle = showAlert || isActive;

  const svg = (
    <svg
      width="24"
      height="24"
      viewBox="0 0 32 32"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={onClick ? "block h-full w-full" : className}
    >
      {/* Bee body - black by default, full yellow when isActive */}
      <motion.path
        d={BEE_BODY_PATH}
        initial={{ fill: "#202020" }}
        animate={{
          fill: fillColor,
          transition: { duration: 0.3, ease: "easeOut" },
        }}
      />

      {/* Flower part - spins with physics and turns red */}
      <motion.g
        style={{
          transformOrigin: "24px 8px",
          transformBox: "fill-box",
        }}
        initial={{ rotate: 0 }}
        animate={
          showAlert
            ? {
                rotate: 720,
                transition: {
                  rotate: {
                    type: "spring",
                    stiffness: 80,
                    damping: 12,
                    mass: 0.8,
                  },
                },
              }
            : {}
        }
      >
        <motion.path
          d={FLOWER_PATH}
          initial={{ fill: "#202020" }}
          animate={{
            fill: flowerFill,
            transition: {
              fill: {
                delay: isActive ? 0 : 0.15,
                duration: 0.4,
                ease: "easeOut",
              },
            },
          }}
        />
      </motion.g>

      {/* Alert circle - red or yellow when active */}
      <motion.circle
        cx="24"
        cy="8"
        r="2"
        fill={circleFill}
        initial={{ opacity: 0, scale: 0 }}
        animate={
          showCircle
            ? {
                opacity: 1,
                scale: 1,
                transition: {
                  delay: isActive ? 0 : 0.35,
                  type: "spring",
                  stiffness: 400,
                  damping: 20,
                },
              }
            : {}
        }
      />
    </svg>
  );

  if (onClick) {
    return (
      <button
        type="button"
        onClick={onClick}
        className={`touch-manipulation shrink-0 ${className ?? ""}`}
        aria-label="Open Beeline"
      >
        {svg}
      </button>
    );
  }
  return <span className={className}>{svg}</span>;
}
